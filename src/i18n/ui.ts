type Keys = keyof (typeof ui)['en'];

/** Returns a translator for a language: const t = useT('fr'); t('nav.apps') */
export function useT(lang: Lang) {
  return function t<K extends Keys>(key: K, vars?: Record<string, string>): (typeof ui)['en'][K] {
    let value = (ui[lang] as Record<Keys, unknown>)[key] ?? ui.en[key];
    if (typeof value === 'string' && vars) {
      for (const [k, v] of Object.entries(vars)) value = (value as string).replaceAll(`{${k}}`, v);
    }
    return value as (typeof ui)['en'][K];
  };
}
